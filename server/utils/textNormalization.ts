/**
 * Text Normalization Utilities
 * أدوات معالجة وتطبيع النصوص العربية والأسماء
 */

/**
 * تطبيع النصوص والأسماء العربية للمقارنة الذكية:
 * 1. إزالة حركات التشكيل والتنوين (فتحة، ضمة، كسرة، سكون، شدة، تنوين).
 * 2. إزالة الكشيدة / التطويل (ـ).
 * 3. توحيد أشكال الألف: [أ، إ، آ، ٱ] -> ا.
 * 4. توحيد الألف المقصورة والياء: ى -> ي.
 * 5. توحيد التاء المربوطة والهاء: ة -> ه.
 * 6. إزالة المحارف غير المرئية ومسافات العرض الصفري (Zero-width characters).
 * 7. إزالة المسافات الزائدة من البداية والنهاية وضغط المسافات البينية المتعددة.
 */
export function normalizeArabicText(text: string | null | undefined): string {
  if (!text) {
    return '';
  }

  return (
    text
      // 1. إزالة التشكيل والتنوين
      .replace(/[\u064B-\u065F\u0670]/g, '')
      // 2. إزالة الكشيدة / التطويل
      .replace(/\u0640/g, '')
      // 3. توحيد أشكال الألف
      .replace(/[أإآٱ]/g, 'ا')
      // 4. توحيد الياء والألف المقصورة
      .replace(/ى/g, 'ي')
      // 5. توحيد التاء المربوطة
      .replace(/ة/g, 'ه')
      // 6. إزالة الحروف غير المرئية ومحارف التوجيه الخفية
      .replace(/[\u200B-\u200D\uFEFF\u200E\u200F]/g, '')
      // 7. توحيد المسافات
      .replace(/\s+/g, ' ')
      .trim()
      .toLowerCase()
  );
}
